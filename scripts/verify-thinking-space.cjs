const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
 const browser = await chromium.launch({headless:true});
 const page = await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
 const errors=[]; page.on('pageerror',error=>errors.push(error.message));
 await page.goto('http://127.0.0.1:5187/redesign.html');
 await page.getByRole('heading',{name:'What could our shared courtyard become?'}).waitFor();
 await page.getByRole('textbox',{name:'Share a thought',exact:true}).fill('Could we use drought-tolerant plants?');
 await page.getByRole('button',{name:'Send message',exact:true}).click();
 await page.getByText('Could we use drought-tolerant plants?',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Reply',exact:true}).first().click();
 await page.getByRole('button',{name:'Cancel reply'}).waitFor();
 await page.getByRole('button',{name:'Cancel reply'}).click();
 await page.getByRole('button',{name:'Proposals',exact:false}).filter({hasText:'Proposals'}).first().click();
 const ratings=page.getByRole('group',{name:'Evaluate: A shared garden, with a place to sit',exact:true});
 await ratings.getByRole('button',{name:'Strongly support',exact:true}).click();
 assert.equal(await ratings.getByRole('button',{name:'Strongly support',exact:true}).getAttribute('aria-pressed'),'true');
 await ratings.getByRole('button',{name:'Neutral',exact:true}).click();
 assert.equal(await ratings.getByRole('button',{name:'Neutral',exact:true}).getAttribute('aria-pressed'),'true');
 await page.getByRole('button',{name:'See 3 original contributions',exact:false}).click();
 await page.getByRole('dialog').getByText('Original contribution 3',{exact:true}).waitFor();
 await page.keyboard.press('Escape');
 await page.getByRole('button',{name:'Add an idea',exact:true}).click();
 await page.getByLabel('Your proposal',{exact:true}).fill('Plant drought-tolerant herbs in portable containers');
 await page.getByRole('button',{name:'Add proposal',exact:true}).click();
 await page.getByRole('heading',{name:'Plant drought-tolerant herbs in portable containers'}).first().waitFor();
 await page.getByRole('button',{name:'Home',exact:true}).click();
 await page.getByRole('searchbox',{name:'Find a conversation'}).fill('courtyard');
 assert.equal(await page.getByRole('heading',{name:'What could our shared courtyard become?'}).count(),1);
 await page.getByRole('searchbox',{name:'Find a conversation'}).fill('not-in-any-conversation');
 await page.getByRole('heading',{name:'No conversations found'}).waitFor();
 await page.getByRole('button',{name:'Clear search',exact:true}).click();
 await page.screenshot({path:'/tmp/freedi-redesign-home.png'});
 await page.getByRole('button',{name:'Start something'}).click();
 await page.getByLabel('Your question',{exact:true}).fill('How can we make our street quieter?');
 await page.getByRole('dialog').getByRole('button',{name:'Start conversation',exact:true}).click();
 await page.getByRole('heading',{name:'How can we make our street quieter?'}).waitFor();
 await page.goto('http://127.0.0.1:5187/redesign.html');
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('heading',{name:'What could our shared courtyard become?'}).waitFor();
 await page.screenshot({path:'/tmp/freedi-redesign-mobile.png'});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'No mobile horizontal overflow');
 await page.getByRole('button',{name:'Taking shape',exact:true}).click();
 await page.getByRole('heading',{name:'Taking shape',exact:true}).waitFor();
 await page.getByRole('button',{name:'Close',exact:true}).click();
 await page.getByRole('button',{name:'Your spaces',exact:true}).click();
 await page.getByRole('navigation',{name:'Your spaces'}).getByRole('button',{name:'Your conversations'}).click();
 await page.getByRole('heading',{name:'Your conversations',exact:true}).waitFor();
 await page.getByRole('button',{name:'RTL',exact:true}).click();
 assert.equal(await page.locator('.thinking-space').getAttribute('dir'),'rtl');
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'No RTL horizontal overflow');
 await page.screenshot({path:'/tmp/freedi-redesign-mobile-rtl.png'});
 await page.getByRole('button',{name:'Dark theme'}).click();
 await page.screenshot({path:'/tmp/freedi-redesign-dark.png'});
 assert.deepEqual(errors,[]);
 console.log('PASS: send/reply, proposal creation, updateable evaluations, source provenance, search and empty state, conversation creation, mobile navigation, mobile board, RTL, dark theme, no runtime errors.');
 await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
