#!/usr/bin/env python3
"""
Split the Open Sans and Roboto variable fonts into unicode-range subsets.

Why: the full multi-script variable files were ~500 KB of every first load
(1/3 of the page on slow 4G). Browsers only download a subset whose
unicode-range matches characters actually on the page, so a Hebrew or English
reader now fetches the latin (+ hebrew) pieces only.

What it does, per source font in packages/shared-styles/src/fonts:
  1. Pins the `wdth` axis at 100 (the app never sets font-stretch, so glyph
     shapes are identical to what rendered before). The `wght` axis is kept
     whole, so every weight renders exactly as before.
  2. Splits the glyphs into latin / latin-ext / hebrew (Open Sans only) and a
     catch-all "other" file holding EVERY remaining codepoint (cyrillic,
     greek, vietnamese, symbols...) so no character loses coverage.
  3. Keeps all OpenType layout features (Hebrew mark positioning, kerning).
  4. Rewrites fonts.css with one @font-face per subset (font-display: swap).

Usage (needs fonttools + brotli):
  python3 -m venv /tmp/ft && /tmp/ft/bin/pip install fonttools brotli
  /tmp/ft/bin/python scripts/subset-fonts.py
"""

import os
import subprocess
import sys
import tempfile

from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = os.path.join(os.path.dirname(__file__), '..', 'packages', 'shared-styles', 'src', 'fonts')
OUT_DIR = os.path.join(ROOT, 'subset')

# Ranges follow Google Fonts' own css2 split.
LATIN = (
    'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,'
    'U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD'
)
LATIN_EXT = (
    'U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,'
    'U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,'
    'U+2C60-2C7F,U+A720-A7FF'
)
HEBREW = 'U+0307-0308,U+0590-05FF,U+200C-2010,U+20AA,U+25CC,U+FB1D-FB4F'

# (source file, output prefix, family, style, weight range, has hebrew glyphs)
SOURCES = [
    ('Open_Sans/OpenSans-VariableFont_wdth,wght.woff2', 'open-sans', 'Open Sans', 'normal', '300 800', True),
    ('Open_Sans/OpenSans-Italic-VariableFont_wdth,wght.woff2', 'open-sans-italic', 'Open Sans', 'italic', '300 800', True),
    ('Roboto/Roboto-VariableFont_wdth,wght.woff2', 'roboto', 'Roboto', 'normal', '100 900', False),
    ('Roboto/Roboto-Italic-VariableFont_wdth,wght.woff2', 'roboto-italic', 'Roboto', 'italic', '100 900', False),
]

CSS_HEADER = '''/*
 * GENERATED by scripts/subset-fonts.py - do not edit by hand.
 *
 * Open Sans + Roboto variable fonts (wght axis intact, wdth pinned at 100),
 * split by unicode-range: the browser downloads only the files whose range
 * covers characters on the page (latin + hebrew for a Hebrew reader).
 * Roboto has no Hebrew glyphs; Hebrew under `font-family: Roboto` falls back
 * exactly as before.
 */
'''


def font_face(family, style, weight, file_name, unicode_range):
    return (
        '@font-face {\n'
        f"    font-family: '{family}';\n"
        f"    src: url('./subset/{file_name}') format('woff2');\n"
        f'    font-weight: {weight};\n'
        f'    font-style: {style};\n'
        '    font-display: swap;\n'
        f'    unicode-range: {unicode_range};\n'
        '}\n'
    )


def parse_ranges(spec):
    points = set()
    for part in spec.split(','):
        part = part.strip().removeprefix('U+')
        if '-' in part:
            lo, hi = part.split('-')
            points.update(range(int(lo, 16), int(hi, 16) + 1))
        else:
            points.add(int(part, 16))

    return points


def to_ranges(points):
    ordered = sorted(points)
    ranges = []
    start = prev = ordered[0]
    for cp in ordered[1:]:
        if cp == prev + 1:
            prev = cp
            continue
        ranges.append((start, prev))
        start = prev = cp
    ranges.append((start, prev))

    return ','.join(f'U+{a:04X}' if a == b else f'U+{a:04X}-{b:04X}' for a, b in ranges)


def subset(src_ttf, unicodes, out_path):
    subprocess.run(
        [
            sys.executable, '-m', 'fontTools.subset', src_ttf,
            f'--unicodes={unicodes}',
            '--layout-features=*',
            '--flavor=woff2',
            f'--output-file={out_path}',
        ],
        check=True,
    )


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    faces = []
    with tempfile.TemporaryDirectory() as tmp:
        for rel, name, family, style, weight, has_hebrew in SOURCES:
            font = TTFont(os.path.join(ROOT, rel))
            cmap = set(font.getBestCmap())
            pinned = instancer.instantiateVariableFont(font, {'wdth': 100})
            pinned.flavor = None
            ttf = os.path.join(tmp, f'{name}.ttf')
            pinned.save(ttf)

            groups = [('latin', LATIN), ('latin-ext', LATIN_EXT)]
            if has_hebrew:
                groups.append(('hebrew', HEBREW))
            covered = set()
            for _, spec in groups:
                covered |= parse_ranges(spec)
            rest = cmap - covered
            groups.append(('other', to_ranges(rest)))

            for group, spec in groups:
                in_font = parse_ranges(spec) & cmap
                if not in_font:
                    continue
                out = os.path.join(OUT_DIR, f'{name}-{group}.woff2')
                subset(ttf, spec, out)
                faces.append(font_face(family, style, weight, os.path.basename(out), spec))
                print(f'{name}-{group}: {os.path.getsize(out) // 1024} KB')

    with open(os.path.join(ROOT, 'fonts.css'), 'w', encoding='utf-8') as css:
        css.write(CSS_HEADER + '\n' + '\n'.join(faces))


if __name__ == '__main__':
    main()
